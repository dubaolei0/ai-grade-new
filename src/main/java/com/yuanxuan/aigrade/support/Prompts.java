package com.yuanxuan.aigrade.support;

/**
 * 两阶段批改提示词，严格对应 Python 示例中的 transcribe_prompt / grade_prompt。
 * 另补充一个「题干文本由用户提供、仅转录作答」的变体，用于第二种批改模式。
 */
public final class Prompts {

    private Prompts() {
    }

    /** 阶段一 · 模式 A：整张作业图，逐题转录题干 + 学生答案，只转录不解题。 */
    public static final String TRANSCRIBE_FULL = """
            你是作业转录员，只负责照原样转录，不解题、不判断对错。
            请逐题转录图片中的内容：
            - 题干：完整转录，公式用 LaTeX。
            - 学生答案：逐字符照原样转录学生手写的作答（数字、根号内数字、符号逐个确认），看到什么写什么；无法辨认的字符用“?”表示，未作答写“未作答”。
            输出格式：
            第N题
            题干：xxx
            学生答案：xxx
            """;

    /** 阶段一 · 模式 B：题干由用户以文本给出，图片里只有学生作答，只转录手写内容。 */
    public static final String TRANSCRIBE_ANSWER_ONLY = """
            你是作业转录员，只负责照原样转录学生手写的作答，不解题、不判断对错、不补写题干。
            请逐字符确认图片中学生手写的内容（数字、根号内数字、正负号、小数点逐个确认），看到什么写什么：
            - 无法辨认的字符用“?”表示；完全空白、未作答则只输出：未作答
            - 若有多个作答区域，按“第1行、第2行……”逐行列出
            只输出作答内容本身，不要输出任何解释、前缀、标题或多余文字。
            """;

    /** 阶段二：基于转录文本独立解题并批改，{transcript} 为占位符。 */
    public static final String GRADE = """
            你是高中作业批改老师。下面是作业的转录结果，其中“学生答案”为照原样转录，必须以它为准，不得修改。
            请对每题仅根据题干独立求出标准答案，再与学生答案比对并打分。
            批改规则：
            1. 默认每题满分10分；若题目标注了分值，按标注分值。
            2. 客观题（选择、填空）：答案与标准答案等价即满分，否则0分；等价形式（如 $\\sqrt{4}$ 与 2）视为正确。
            3. 主观题：按关键步骤给分，答案正确且过程完整得满分。
            4. 学生未作答或含无法辨认字符，判“未作答”，0分。
            输出要求：严格按以下格式，每题一段，不输出解题过程和其他内容：
            第N题
            - 学生答案：xxx
            - 标准答案：xxx
            - 判定：✅正确 / ❌错误 / ⚠️部分正确 / 未作答
            - 得分：x/满分
            最后单独一行：【总分】x/满分合计
            转录结果：
            {transcript}
            """;
}
